import { describe, expect, it } from 'vitest';
import {
  currentRequestContext,
  currentRequestId,
  requestContextFrom,
  withRequestContext,
} from './requestContext';

const proxyId = '6f1c2a5e-8b9d-4e3f-a1b2-c3d4e5f60718';

describe('requestContextFrom', () => {
  it('keeps the id generated by the proxy and the first forwarded IP', () => {
    const headers = new Headers({
      'x-request-id': proxyId,
      'x-forwarded-for': '203.0.113.12, 10.0.0.1',
    });
    expect(requestContextFrom(headers)).toEqual({ requestId: proxyId, ipAddress: '203.0.113.12' });
  });

  it('replaces a malformed id and omits an unknown IP', () => {
    const forged = `abc","userId":"admin${'x'.repeat(200)}`;
    const context = requestContextFrom(new Headers({ 'x-request-id': forged }));
    expect(context.requestId).not.toContain('abc');
    expect(context.requestId).toMatch(/^[0-9a-f-]{36}$/);
    expect(context.ipAddress).toBeUndefined();
  });
});

describe('withRequestContext', () => {
  it('exposes the context through awaits and clears it afterwards', async () => {
    const headers = new Headers({ 'x-request-id': proxyId });
    const seen = await withRequestContext(headers, async () => {
      await Promise.resolve();
      return currentRequestId();
    });

    expect(seen).toBe(proxyId);
    expect(currentRequestContext()).toBeUndefined();
  });

  it('keeps the outer context when nested, so one request has a single id', async () => {
    const outer = new Headers({ 'x-request-id': proxyId });
    const inner = await withRequestContext(outer, () =>
      withRequestContext(new Headers(), async () => currentRequestId())
    );

    expect(inner).toBe(proxyId);
  });

  it('isolates concurrent requests', async () => {
    const ids = ['11111111-1111-4111-8111-111111111111', '22222222-2222-4222-8222-222222222222'];
    const seen = await Promise.all(
      ids.map((id, index) =>
        withRequestContext(new Headers({ 'x-request-id': id }), async () => {
          await new Promise((resolve) => setTimeout(resolve, 10 - index * 5));
          return currentRequestId();
        })
      )
    );

    expect(seen).toEqual(ids);
  });

  it('falls back to a fresh id outside a request', () => {
    expect(currentRequestId()).not.toBe(currentRequestId());
  });
});
